def build_batch_category_prompt(
    items: List[Dict[str, Any]],
    store: str,
) -> str:
    """
    여러 상품을 한 번에 분류할 때 사용할 프롬프트.
    현재 운영에서는 단건 분류를 권장하지만,
    비용 절감이 필요하면 batch 호출에 사용할 수 있다.
    """

    category_list = ", ".join(
        category
        for category in PRIMARY_CATEGORIES
        if category != "Uncategorized"
    )

    basket_names = [
        _safe_str(item.get("name"))
        for item in items
        if _safe_str(item.get("name"))
    ]

    basket_context = _format_basket_items(
        basket_items=basket_names,
        current_item_name=None,
    )

    item_lines = []
    for idx, item in enumerate(items, start=1):
        item_lines.append(
            f"{idx}. 상품명={_safe_str(item.get('name'))}, "
            f"수량={_format_optional_number(_safe_int(item.get('qty')))}, "
            f"단가={_format_money(_safe_int(item.get('unit_price')))}, "
            f"할인전금액={_format_money(_safe_int(item.get('base_price')))}, "
            f"할인금액={_format_money(_safe_int(item.get('discount')) or 0)}, "
            f"최종금액={_format_money(_safe_int(item.get('final_price')))}"
        )

    return f"""너는 마트 영수증 상품을 소비 분석용 카테고리로 분류하는 보조 모델이다.

반드시 아래 허용 카테고리 중 하나만 선택해야 한다.

[허용 카테고리]
{category_list}

{COMPACT_CATEGORY_RULES}

[구매처]
{store}

[장바구니 전체 문맥]
{basket_context}

[분류 대상 상품 목록]
{chr(10).join(item_lines)}

[출력 규칙]
1. 각 상품 번호에 대해 허용 카테고리 중 하나만 선택한다.
2. 설명을 쓰지 않는다.
3. JSON 배열로만 출력한다.
4. 각 원소는 item_no와 category만 가진다.
5. 반려동물 상품은 기타로 출력한다.

[출력 예시]
[
  {{"item_no": 1, "category": "식재료"}},
  {{"item_no": 2, "category": "간식"}}
]"""


def _format_basket_items(
    basket_items: Optional[Iterable[str]],
    current_item_name: Optional[str] = None,
    max_items: int = 20,
) -> str:
    if not basket_items:
        return "- 없음"

    current = _safe_str(current_item_name)
    names: List[str] = []

    for name in basket_items:
        safe_name = _safe_str(name)

        if not safe_name:
            continue

        if current and safe_name == current:
            continue

        names.append(safe_name)

    if not names:
        return "- 없음"

    unique_names = []
    seen = set()

    for name in names:
        if name in seen:
            continue

        seen.add(name)
        unique_names.append(name)

    limited_names = unique_names[:max_items]

    lines = [f"- {name}" for name in limited_names]

    if len(unique_names) > max_items:
        lines.append(f"- ... 외 {len(unique_names) - max_items}개")

    return "\n".join(lines)


def _safe_str(value: Any) -> str:
    if value is None:
        return ""

    return str(value).strip()


def _safe_int(value: Any) -> Optional[int]:
    if value is None:
        return None

    try:
        return int(value)
    except Exception:
        return None


def _format_money(value: Optional[int]) -> str:
    if value is None:
        return "알 수 없음"

    return f"{value:,}원"


def _format_optional_number(value: Optional[int]) -> str:
    if value is None:
        return "알 수 없음"

    return f"{value:,}"